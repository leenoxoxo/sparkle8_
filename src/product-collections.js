const slugify = value => value.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
export function organizeProducts(existingProducts) {
  const groups = new Map();
  for (const entry of collectionEntries.filter(e => !e.galleryOnly)) {
    if (!groups.has(entry.name)) groups.set(entry.name, []);
    groups.get(entry.name).push(entry);
  }
  const replacements = new Map(), additions = [];
  let nextOrder = Math.max(...existingProducts.map(p => p.addedOrder || 0)) + 1;
  for (const [name, entries] of groups) {
    const owners = existingProducts.filter(p => entries.some(e => e.existing === p.slug));
    const base = owners[0];
    const first = base ? entries.find(e => e.existing === base.slug && decodeURIComponent(base.image.split('/').pop()) === e.file) || entries.find(e => e.existing === base.slug) : entries[0];
    const category = base?.category || (name.includes('Mirror') ? 'Mirrors' : name.includes('Brush') ? 'Brushes' : name.includes('Case') ? 'Phone Cases' : 'Boxes');
    const galleryEntries = collectionEntries.filter(entry => entry.galleryFor === name);
    const galleryImages = galleryEntries.map(entry => '/SHOP%20IMGS/' + encodeURIComponent(entry.file));
    const variants = entries.map(entry => {
      const owner = existingProducts.find(p => p.slug === entry.existing);
      const sourceImage = '/SHOP%20IMGS/' + encodeURIComponent(entry.file);
      const primaryEntry = owner && (entries.find(e => e.existing === owner.slug && decodeURIComponent(owner.image.split('/').pop()) === e.file) || entries.find(e => e.existing === owner.slug));
      const image = owner && primaryEntry === entry ? owner.image : sourceImage;
      const price = entry.price ?? owner?.price ?? base?.price ?? 'Message us';
      const originalPrice = entry.originalPrice ?? owner?.originalPrice ?? base?.originalPrice;
      const amount = value => Number.parseFloat(String(value).replace(/[^0-9.]/g, ''));
      const discountPercent = amount(originalPrice) > amount(price) ? Math.round((amount(originalPrice) - amount(price)) / amount(originalPrice) * 100) : undefined;
      return { id: slugify(entry.variant || entry.name), name: entry.variant || entry.name, colors: variantColors[entry.variant], file: entry.file, image, images:[...new Set([image, ...(owner?.images || []), ...galleryImages])], price, originalPrice, discountPercent, status:owner?.status || base?.status || 'Available to order' };
    });
    const selected = variants[entries.indexOf(first)];
    const product = { ...(base || {slug:slugify(name),addedOrder:nextOrder++,category,status:'Available to order',price:'Message us',tone:'cream',icon:'✨',details:['Message us on Instagram']}), name, price:selected.price, originalPrice:selected.originalPrice, discountPercent:selected.discountPercent, collection:entries[0].collection, description:entries[0].description || base?.description, image:base?.image || selected.image, images:base?.images || selected.images, variants:entries.some(e => e.variant) ? variants : undefined, defaultVariant:selected.id, sourceFiles:entries.map(e => e.file), aliases:owners.slice(1).map(owner => ({slug:owner.slug,variant:variants[entries.findIndex(e => e.existing === owner.slug)].id})) };
    product.aliases.push(...galleryEntries.filter(entry => entry.legacySlug).map(entry => ({slug:entry.legacySlug, variant:selected.id})));
    for (const owner of owners) replacements.set(owner.slug,product);
    if (!owners.length) additions.push(product);
  }
  const seen = new Set();
  return [...existingProducts.map(p => replacements.get(p.slug) || p),...additions].filter(p => {if(seen.has(p.slug))return false;seen.add(p.slug);return true;}).map((p,index)=>({...p,defaultOrder:index,priceValue:Number.parseFloat(p.price.replace(/[^0-9.]/g,''))}));
}
export function resolveProduct(products, slug) {
  const product = products.find(p => p.slug === slug || p.aliases?.some(alias => alias.slug === slug));
  if (!product) return undefined;
  const alias = product.aliases?.find(alias => alias.slug === slug);
  return alias ? {...product,defaultVariant:alias.variant} : product;
}
